#!/usr/bin/env bash
# ==================================================
# セッション状態ファイルのパスを決める（共通処理）
# ==================================================
# PreCompact 側（書く）と SessionStart 側（読む）で同じパスを指す必要がある。
# 片方だけ変えると保存したのに復旧しない状態になり、しかもエラーが出ないので
# 気づけない。ここに 1 本化する。
#
# 使い方: source して session_state_path <cwd> を呼ぶ。
#
# セッション ID ではなく cwd から決める理由:
#   - モデル自身が判断ログを追記するとき、cwd は分かるが session_id は分からない
#   - 同じディレクトリで並行するセッションは同じ作業を見ているので、共有して困らない
#   - セッションをまたいで残るため、翌日の再開でも判断が読める

session_state_path() {
  local cwd="${1:-$PWD}"
  # パス区切りを - に潰す。先頭の / も - になるので Claude Code の
  # projects ディレクトリと同じ命名になる。
  local key
  key="$(printf '%s' "$cwd" | sed 's/[^A-Za-z0-9]/-/g')"
  printf '%s/.claude/session-state/%s.md' "$HOME" "$key"
}
